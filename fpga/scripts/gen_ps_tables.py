#!/usr/bin/env python
"""Emit the C tables of the fixed-point model (Gaussian LUT + device step / pulse-index tables) from bpusim.fixed,
so the firmware and the reference can never drift apart."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[2]))
from bpusim import fixed as F
out = pathlib.Path(sys.argv[1])
t = F.tables(); z = F.gaussian_lut()
def arr(name, ctype, vals):
    body = ",\n".join("    " + ", ".join(str(int(v)) for v in vals[i:i + 16]) for i in range(0, len(vals), 16))
    return f"const {ctype} {name}[{len(vals)}] = {{\n{body}\n}};\n"
src = "/* generated by fpga/scripts/gen_ps_tables.py from bpusim/fixed.py -- do not edit */\n#include \"bpu_fixed.h\"\n"
src += arr("bpu_zlut", "int16_t", z) + arr("bpu_step_up", "uint16_t", t["STEP_UP"]) + arr("bpu_step_dn", "uint16_t", t["STEP_DN"])
src += arr("bpu_nup", "uint16_t", t["NUP"]) + arr("bpu_ndn", "uint16_t", t["NDN"])
out.write_text(src); print(out)
